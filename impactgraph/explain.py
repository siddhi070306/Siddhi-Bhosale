"""Plain-English explanations built from the knowledge graph's own facts.

explain_link   one relationship: what it says, why it exists, how it was identified, what market data says about it, how
               its score is calculated, and how long it takes to show.
explain_chain  one impact chain from an event to an affected entity: the chain told step by step with each step's reason,
               the evidence behind every step, the arithmetic of the chain's score, its weakest step, and what it concludes.

Every sentence is built from what the graph stores (sign, strength, lag, mechanism, provenance, article evidence, data
check), so the same graph always reads the same way and every number in the text can be checked against the graph.
Nothing here is generated by a language model.
"""
from . import kb, propagate as pg

_PRIOR = {(s, d): st for s, d, _sign, st, _lag, _why in kb.EDGES}
_RELATION = {
    "member_of": "{b} is a member of the {a} sector, so it tends to move with the sector.",
    "tracks": "{b} is a fund or index that follows {a}.",
    "weight_in": "{a} is part of {b}, so its moves feed into that index.",
    "policy_reaction": "{a}'s decisions reprice {b}.",
}


def _label(g, n):
    return g.nodes[n]["label"]


def _band(x):
    return "strong" if x >= 0.6 else "moderate" if x >= 0.35 else "weak"


def _days(n):
    n = int(round(n or 0))
    return "the same day" if n == 0 else "about 1 day" if n == 1 else "about %d days" % n


def _rise_in(g, n):
    """'a rise in Crude Oil', 'a rise in the Airlines sector', 'a hawkish move by the US Federal Reserve': reads correctly
    whether the name is singular or plural."""
    lab, typ = _label(g, n), g.nodes[n]["type"]
    if typ == "institution":
        return "a hawkish move by %s (a rate rise or a tighter stance)" % ("the " + lab if lab.startswith("US ") else lab)
    if typ == "sector":
        return "a rise in the %s sector" % lab
    return "a rise in %s" % _named(g, n)


def _named(g, n):
    """'the S&P 500', 'the Nifty 50'; other names as they are."""
    lab = _label(g, n)
    return ("the " if g.nodes[n]["type"] == "index" or lab.startswith("US ") else "") + lab


def _quote(s, n=180):
    """The sentence in quotation marks, ending with its own full stop inside them (so no '.".' doubling)."""
    s = " ".join((s or "").split())
    s = s if len(s) <= n else s[:n - 1].rstrip() + "…"
    return "“%s%s”" % (s, "" if s.endswith((".", "!", "?", "…")) else ".")


def explain_link(kg, u, v):
    """-> dict with the explanation in parts (headline, why, identified, data, score, timing, relation) and as one text."""
    g = kg.g
    e = g[u][v]
    a, b = _label(g, u), _label(g, v)
    prov = set(e.get("provenance") or [])
    val = e.get("validation") or {}
    same = e["sign"] > 0

    target = ("the %s sector" % b) if g.nodes[v]["type"] == "sector" else _named(g, v)
    rise = _rise_in(g, u)
    headline = "%s%s tends to push %s %s." % (rise[0].upper(), rise[1:], target, "up" if same else "down")
    mech = (e.get("mechanism") or "").replace("User-added: ", "").replace(" (LLM-proposed, quote-verified)", "").strip().rstrip(".")
    rel = _RELATION.get(e.get("relation"))
    relation = rel.format(a=a, b=b) if rel else None
    if relation and len(mech) < 30:            # "Sector member" says less than the relation does
        why, relation = "Why: " + relation[0].lower() + relation[1:] if relation.startswith("The ") else "Why: " + relation, None
    else:
        why = "Why: %s." % (mech[0].lower() + mech[1:] if mech else "no reason is recorded for this link")

    # how the relationship was identified
    ident = []
    if "prior" in prov:
        ident.append("An analyst wrote this link into the knowledge graph as a known economic relationship.")
    if "llm_proposed" in prov:
        ident.append("The language model proposed it while reading an article, and the sentence it relied on was found word for "
                     "word in that article.")
    if "user_added" in prov:
        ident.append("A user added this link.")
    if "inferred" in prov and not prov & {"prior", "llm_proposed", "user_added"}:
        ident.append("The system inferred it from a company's name; it has not been verified.")
    ev = e.get("evidence") or []
    rule_ev = [x for x in ev if x.get("by") != "llm"]
    llm_ev = [x for x in ev if x.get("by") == "llm"]
    if rule_ev:
        ident.append("%d analysed article sentence%s mention%s both, for example: %s" % (
            len(rule_ev), "" if len(rule_ev) == 1 else "s", "s" if len(rule_ev) == 1 else "", _quote(rule_ev[-1]["sentence"])))
    if llm_ev and "llm_proposed" not in prov:
        ident.append("The language model also read it in an article (the quote was verified): %s" % _quote(llm_ev[-1]["sentence"]))
    if "user_edited" in prov:
        ident.append("A user has changed its weight.")

    # market data check
    if not val.get("verdict"):
        data = "It has not been checked against market data in this analysis."
    elif val.get("simulated"):
        data = "Only simulated data was available, so no data check is used for this link."
    elif val["verdict"] in ("supported", "contradicted"):
        moved = "the same way" if val["corr"] > 0 else "the opposite way"
        when = "on the same day" if not val.get("lag_days") else "%d day%s later" % (val["lag_days"], "" if val["lag_days"] == 1 else "s")
        data = ("Market data %s: over %d trading days, when %s moved, %s moved %s %s (correlation %+.2f)%s." % (
            "agrees" if val["verdict"] == "supported" else "disagrees", val.get("n") or 0, a, b, moved, when, val["corr"],
            ", as the link expects" if val["verdict"] == "supported" else ", which is the opposite of what the link expects"))
    elif val["verdict"] == "inconclusive":
        data = ("Market data was checked over %d trading days, but the relationship was too weak to confirm or reject "
                "(correlation %+.2f)." % (val.get("n") or 0, val.get("corr") or 0))
    elif val["verdict"] == "same_series":
        data = "Both are measured by the same market series, so market data cannot check this link independently."
    else:
        data = "There is no market data for one of them, so the link rests on the analyst's judgement and article evidence."

    # how the score is calculated
    stored, eff = e["strength"], kg.eff_strength(u, v)
    start = _PRIOR.get((u, v), e.get("base_strength", stored))
    who = ("a user" if "user_edited" in prov or "user_added" in prov else "the analyst" if "prior" in prov
           else "the language model's starting value" if "llm_proposed" in prov else "the system")
    if "user_edited" in prov or "user_added" in prov:
        start = e.get("base_strength", stored)          # the value the user set; later article evidence shows as its own step
        if "user_edited" in prov and (u, v) in _PRIOR and abs(start - _PRIOR[(u, v)]) < 0.0005:
            who = "the analyst (a user restored this value)"
    steps = ["it starts at %.2f, set by %s" % (start, who)]
    if abs(stored - start) >= 0.0005:
        steps.append("article evidence %s it to %.2f" % ("raised" if stored > start else "lowered", stored))
    mult = val.get("multiplier", 1.0) if val.get("adjusts") else 1.0
    if abs(mult - 1.0) >= 0.0005:
        capped = stored * mult > 0.99 + 1e-9
        steps.append("market data %s it by %d%% to %.2f%s" % ("raised" if mult > 1 else "lowered", round(abs(mult - 1) * 100), eff,
                                                            " (the most any link can score)" if capped else ""))
    decay = pg._edge_decay(e)
    decay_why = {pg.DECAY_STRONG: "the data support is strong (correlation of 0.50 or more)",
                 pg.DECAY_MODERATE: "the data support is moderate (correlation between 0.30 and 0.50)",
                 pg.DECAY_WEAK: "the data support is weak (correlation below 0.30) or the data disagrees",
                 pg.DECAY_DEFAULT: "it has not been checked against market data"}
    score = ("Score: %.2f out of 1 (%s). %s. When this link is a later step in a chain, it is also discounted by %.2f, because %s. "
             "This is a plausibility score (how likely and material the link is), not a probability or a price move." % (
                 eff, _band(eff), "; ".join(steps)[0].upper() + "; ".join(steps)[1:], decay, decay_why.get(decay, "of its data check")))
    lag, base_lag = kg.eff_lag(u, v), e.get("lag", 0)
    timing = "The effect typically shows up %s%s%s." % (
        "on " if int(round(lag or 0)) == 0 else "within ", _days(lag),
        "" if lag == base_lag else " (the analyst's estimate was %s; recent data and market volatility adjusted it)" % _days(base_lag))

    # the same facts as short codes, for badges and counts in the UI
    by = [code for code, ok in (("analyst", "prior" in prov), ("article", bool(rule_ev)),
                                ("llm", bool(llm_ev) or "llm_proposed" in prov), ("user", bool(prov & {"user_added", "user_edited"})),
                                ("inferred", "inferred" in prov and not prov & {"prior", "llm_proposed", "user_added"})) if ok]
    if not val.get("verdict"):
        check = "unchecked"
    elif val.get("simulated"):
        check = "simulated"
    else:
        check = {"supported": "agrees", "contradicted": "disagrees", "inconclusive": "too_weak", "same_series": "same_series"}.get(
            val["verdict"], "no_data")
    parts = [headline, why] + ([relation] if relation else []) + ["How it was identified: " + " ".join(ident)] + [data, score, timing]
    return {"headline": headline, "why": why, "relation": relation, "identified": ident, "data": data, "score": score,
            "timing": timing, "score_value": round(eff, 3), "score_band": _band(eff),
            "score_parts": {"start": round(start, 3), "after_articles": round(stored, 3), "data_multiplier": round(mult, 3),
                            "score": round(eff, 3), "chain_discount": decay},
            "identified_by": by, "data_check": {"result": check, "corr": val.get("corr"), "days": val.get("n"),
                                                "lag_days": val.get("lag_days")},
            "lag_days": lag, "sign": e["sign"], "text": " ".join(parts)}



_MOVE = {1: "rise", -1: "fall"}


def _move_in(g, n, d, det="a"):
    """'a rise in Crude Oil', 'that fall in the Banks sector', 'a hawkish move by the US Federal Reserve'."""
    if g.nodes[n]["type"] == "institution":
        return "%s %s move by %s" % (det, "hawkish" if d > 0 else "dovish", _named(g, n))
    return "%s %s in %s" % (det, _MOVE[d], _target(g, n))


def _target(g, n):
    return ("the %s sector" % _label(g, n)) if g.nodes[n]["type"] == "sector" else _named(g, n)


_WEAK_REASON = {
    "disagrees": "market data disagrees with it",
    "too_weak": "market data is too weak to confirm it",
    "no_data": "there is no market data to check it",
    "same_series": "market data cannot check it independently",
    "unchecked": "it has not been checked against market data",
    "simulated": "only simulated data was available for it",
}


def explain_chain(kg, path, source_event=None, observed=None):
    """One impact chain, explained. `path` is an explained path from the analysis (nodes, steps with the direction each node
    takes, score, horizon); `source_event` the event it starts from; `observed` maps nodes the article reports moving to the
    direction it reports, so a chain that ends on one can say whether it agrees."""
    g = kg.g
    steps_in = path.get("steps") or []
    if not steps_in:
        return None
    dirs = [steps_in[0]["to_dir"] * steps_in[0]["sign"]] + [s["to_dir"] for s in steps_in]

    # how the chain starts: what the article said, or that it is a model hypothesis
    ev = source_event or {}
    status, quote = ev.get("status"), ev.get("quote") or ""
    start_label = ev.get("label") or _label(g, path["nodes"][0])
    if status == "observed":
        opening = "The article reports %s%s." % (start_label, " (%s)" % _quote(quote, 160) if quote else "")
    elif status == "expected":
        opening = "The article expects %s, stated as a possibility rather than as something that happened%s." % (
            start_label, " (%s)" % _quote(quote, 160) if quote else "")
    elif status == "hypothesis":
        opening = "The model suggests %s as a hypothesis; the article does not state it." % start_label
    else:
        opening = "This chain starts from %s." % (path.get("source") or start_label)

    # the chain, step by step, each with its reason and the evidence behind it
    steps, clauses, weakest = [], [], None
    last = len(steps_in) - 1
    for i, s in enumerate(steps_in):
        u, v = s["from"], s["to"]
        link = explain_link(kg, u, v)
        why = link["why"][len("Why: "):] if link["why"].startswith("Why: ") else link["why"]
        why = why.rstrip(".")
        to_word = "up" if dirs[i + 1] > 0 else "down"
        sentence = "%s pushes %s %s" % (_move_in(g, u, dirs[i]), _target(g, v), to_word)
        told = "%s pushes %s %s" % (_move_in(g, u, dirs[i], "a" if i == 0 else "that"), _target(g, v), to_word)
        clauses.append(("and " if i == last and i else "") + told + ", because " + why[0].lower() + why[1:])
        discount = 1.0 if i == 0 else s.get("decay", 1.0)
        weight = s["effective"] * discount
        quotes = [x for x in (s.get("evidence") or []) if x]
        step = {"n": i + 1, "from": u, "to": v, "from_label": _label(g, u), "to_label": _label(g, v),
                "sentence": sentence[0].upper() + sentence[1:] + ".", "why": why[0].upper() + why[1:] + ".",
                "identified_by": link["identified_by"], "data_check": link["data_check"],
                "quote": quotes[-1] if quotes else None, "strength": s["effective"], "discount": discount,
                "weight": round(weight, 3), "lag_days": s.get("lag")}
        steps.append(step)
        if weakest is None or weight < weakest["weight"]:
            weakest = step
    narrative = "; ".join(clauses)
    narrative = narrative[0].upper() + narrative[1:] + "."

    # the evidence behind the chain as a whole
    n = len(steps)
    count = lambda pred: sum(1 for x in steps if pred(x))
    analyst = count(lambda x: "analyst" in x["identified_by"])
    article = count(lambda x: "article" in x["identified_by"])
    llm = count(lambda x: "llm" in x["identified_by"])
    user = count(lambda x: "user" in x["identified_by"])
    agree = count(lambda x: x["data_check"]["result"] == "agrees")
    disagree = count(lambda x: x["data_check"]["result"] == "disagrees")
    weak = count(lambda x: x["data_check"]["result"] == "too_weak")
    unchecked = n - agree - disagree - weak
    parts = ["%d of %d step%s %s written by an analyst" % (analyst, n, "" if n == 1 else "s", "is" if analyst == 1 else "are")]
    if article:
        parts.append("%d %s backed by a sentence in an analysed article" % (article, "is" if article == 1 else "are"))
    if llm:
        parts.append("%d %s read or proposed by the language model with a verified quote" % (llm, "was" if llm == 1 else "were"))
    if user:
        parts.append("%d %s a user's edit" % (user, "carries" if user == 1 else "carry"))
    data_bits = [t for t in ("agrees with %d" % agree if agree else "", "disagrees with %d" % disagree if disagree else "",
                             "is too weak to judge %d" % weak if weak else "") if t]
    if data_bits:
        data_sentence = "Market data %s%s." % (", ".join(data_bits), "; %d %s no independent market-data check" % (
            unchecked, "step has" if unchecked == 1 else "steps have") if unchecked else "")
    else:
        data_sentence = "None of the steps could be checked independently against market data."
    evidence = "Evidence: " + "; ".join(parts) + ". " + data_sentence

    # the chain's score, multiplied out, and its weakest step
    factors = ["%.2f" % steps[0]["strength"]] + ["(%.2f × %.2f)" % (x["strength"], x["discount"]) for x in steps[1:]]
    arithmetic = ("Plausibility %.2f: the steps' scores multiplied together, each step after the first discounted for distance: "
                  "%s = %.2f. Longer and weakly supported chains score lower. This measures how plausible the whole chain is, "
                  "not a probability or the size of a move." % (path["score"], " × ".join(factors), path["score"]))
    weakest_sentence = None
    if n > 1:
        res = weakest["data_check"]["result"]
        why_weak = _WEAK_REASON.get(res, "it is the lowest-scoring link in the chain")
        if res == "agrees":
            why_weak = ("market data supports it only weakly, so it is discounted more" if weakest["discount"] <= pg.DECAY_WEAK
                        else "it is the lowest-scoring link in the chain")
        weakest_sentence = "The weakest step is %s → %s (%.2f after its discount): %s." % (
            weakest["from_label"], weakest["to_label"], weakest["weight"], why_weak)

    end, end_dir = path["nodes"][-1], dirs[-1]
    if observed and end in observed:
        conclusion = "The article itself reports %s moving %s, and this chain %s." % (
            _target(g, end), "up" if observed[end] > 0 else "down",
            "agrees with it" if observed[end] == end_dir else "points the other way, so the graph and the article disagree here")
    else:
        days = round(path.get("horizon_days") or 0)
        conclusion = "So the model infers that %s may move %s%s. This is an inference, not something the article states." % (
            _target(g, end), "up" if end_dir > 0 else "down", " on the same day" if days == 0 else " within about %d days" % days)
    chain_line = " → ".join("%s %s" % (_label(g, nd), "↑" if d > 0 else "↓") for nd, d in zip(path["nodes"], dirs))
    return {"headline": chain_line, "opening": opening, "narrative": narrative, "steps": steps, "evidence": evidence,
            "evidence_counts": {"steps": n, "analyst": analyst, "article": article, "llm": llm, "user": user,
                                "data_agrees": agree, "data_disagrees": disagree, "data_too_weak": weak, "unchecked": unchecked},
            "arithmetic": arithmetic, "weakest": weakest_sentence, "conclusion": conclusion,
            "score": round(path["score"], 3), "score_band": _band(path["score"]), "horizon_days": path.get("horizon_days")}
